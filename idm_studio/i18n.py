def normalize_language(code: str | None) -> str | None:
    """Dil kodunu (tr, tr_TR, tr_TR.UTF-8) desteklenen koda indirger."""
    if not code:
        return None
    value = code.strip().lower().replace("-", "_")
    if value in LANGUAGE_NAMES:
        return value
    base = value.split("_", 1)[0].split(".", 1)[0]
    return base if base in LANGUAGE_NAMES else None


def detect_system_language() -> str:
    """Sistem yerel ayarından desteklenen bir dil seçer."""
    for variable in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        raw = os.environ.get(variable)
        if not raw:
            continue
        for part in raw.split(":"):
            code = normalize_language(part)
            if code:
                return code
    return "en"


_current = detect_system_language()


def get_language() -> str:
    return _current


def set_language(code: str | None) -> str:
    global _current
    normalized = normalize_language(code)
    if normalized:
        _current = normalized
    return _current


def tr(key: str, **kwargs: object) -> str:
    """Etkin dildeki metni döndürür; eksik anahtar için İngilizceye düşer."""
    bundle = STRINGS.get(_current, _EN)
    template = bundle.get(key)
    if template is None:
        template = _EN.get(key, key)
    if not isinstance(template, str):
        return str(template)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return template
    return template


def month_names() -> tuple[str, ...]:
    bundle = STRINGS.get(_current, _EN)
    months = bundle.get("date.months")
    if isinstance(months, tuple) and len(months) == 12:
        return months
    return _EN["date.months"]


def language_name(code: str | None = None) -> str:
    return LANGUAGE_NAMES.get(code or _current, LANGUAGE_NAMES[_current])

